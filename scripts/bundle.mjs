// The bundle step, and the two generated modules that make it a PROJECT's
// bundle rather than the engine's.
//
// Remotion bundles from an entry point and serves a public directory. Here
// they come from two different places: the entry is reelkit's own src/index.ts
// (in node_modules), the public directory is the project's. Two webpack
// aliases carry everything else a project decides:
//
//   reelkit-theme     → .reelkit/theme.ts     generated from reel.config.mjs
//   reelkit-elements  → .reelkit/elements.tsx generated from elements/
//
// Both fall back to core's neutral defaults, so a project with no theme and
// no elements of its own still renders — it just renders in grey.

import { bundle } from "@remotion/bundler";
import { cpSync, existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { config, elementsDir, genDir, kitDir, projectDir, publicDir } from "./project.mjs";
import { CAPTION_DEFAULTS, CAPTION_FACE, SAFE_DEFAULTS } from "../src/lab/subtitles.mjs";

const INKS = ["paper", "ink", "faded", "trace"];
const DEFAULT_MONO =
  '"SF Mono", "SFMono-Regular", ui-monospace, Menlo, Monaco, monospace';

/**
 * Writes .reelkit/theme.ts from the config, or returns null when the project
 * has not themed anything.
 *
 * The palette is validated here rather than at paint time, because a missing
 * ink does not throw — it renders as `undefined`, which CSS reads as "inherit
 * whatever the parent had" and the frame comes out subtly wrong instead of
 * loudly broken. That failure costs a full render to notice.
 */
const writeTheme = () => {
  const theme = config.theme;
  if (!theme) return null;
  for (const mode of ["light", "dark"]) {
    const palette = theme.palettes?.[mode];
    if (!palette) {
      throw Object.assign(
        new Error(`reel.config.mjs: theme.palettes.${mode} is missing.`),
        { fatal: true },
      );
    }
    for (const ink of INKS) {
      if (typeof palette[ink] !== "string") {
        throw Object.assign(
          new Error(
            `reel.config.mjs: theme.palettes.${mode}.${ink} is missing.\n` +
              `All four inks are required in both modes — an absent one paints ` +
              `as "inherit", which renders wrong instead of failing.`,
          ),
          { fatal: true },
        );
      }
    }
  }
  const file = path.join(genDir, "theme.ts");
  writeFileSync(
    file,
    `// GENERATED by reelkit from reel.config.mjs — do not edit.\n` +
      `import type { ThemeModule } from "${path.join(kitDir, "src", "theme.types")}";\n\n` +
      `const theme: ThemeModule = ${JSON.stringify(
        {
          palettes: theme.palettes,
          brand: { wordmark: theme.brand?.wordmark ?? null },
          mono: theme.mono ?? DEFAULT_MONO,
          // Every face falls back to `mono`, so a project that themes nothing
          // renders byte-identically to the version before these existed.
          fonts: {
            display: theme.fonts?.display ?? theme.mono ?? DEFAULT_MONO,
            body: theme.fonts?.body ?? theme.mono ?? DEFAULT_MONO,
            // The caption band alone does NOT fall back to `mono`. The
            // measured look is a sans, the receipt idiom lives in the
            // elements rather than in the words the voice is saying, and
            // theme.default.ts has said so since the promotion — while this
            // line quietly handed SF Mono to every themed project. A project
            // that wants monospaced captions names the face.
            caption: theme.fonts?.caption ?? CAPTION_FACE,
          },
          // THE caption default lives in src/lab/subtitles.mjs, and this line
          // is the whole of what used to be twenty here.
          //
          // What was here was a second copy of it — `?? 48`, `?? 400`,
          // `?? "uppercase"`, `?? true`, the receipt look — and when the
          // measured look was promoted into theme.default.ts on 2026-09-09
          // this copy was not touched. theme.default.ts is what a project
          // with NO theme gets; this is what every project that HAS one
          // gets. So the promotion reached nothing real: every themed
          // project kept rendering 48/400/uppercase in SF Mono while the
          // repo believed it had shipped 66/700 in a sans.
          //
          // A project still overrides any single key, and one that wants the
          // receipt caption back says so — `.parity` does, because that
          // fixture exists to render a TALLY post like Tally.
          captions: { ...CAPTION_DEFAULTS, ...(theme.captions ?? {}) },
          hairline: theme.hairline ?? 3,
          safe: { ...SAFE_DEFAULTS, ...(theme.safe ?? {}) },
        },
        null,
        2,
      )};\n\nexport default theme;\n`,
  );
  return file;
};

/**
 * Writes .reelkit/elements.tsx from the project's elements/ folder, or returns
 * null when there is none.
 *
 * One folder per element, each exporting `component` and `mapCues`. The folder
 * NAME is the element's name in a post spec — so renaming the folder renames
 * the element, and there is no second place to keep in step.
 */
const writeElements = () => {
  if (!existsSync(elementsDir)) return null;
  const names = readdirSync(elementsDir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith("_"))
    .map((e) => e.name)
    .filter((name) =>
      ["index.tsx", "index.ts"].some((f) =>
        existsSync(path.join(elementsDir, name, f)),
      ),
    )
    .sort();
  if (!names.length) return null;

  const imports = names
    .map((name, i) => `import * as e${i} from "${path.join(elementsDir, name, "index")}";`)
    .join("\n");
  const entries = names
    .map(
      (name, i) =>
        `  ${JSON.stringify(name)}: { component: e${i}.component, mapCues: e${i}.mapCues ?? (() => ({})) },`,
    )
    .join("\n");
  const file = path.join(genDir, "elements.tsx");
  writeFileSync(
    file,
    `// GENERATED by reelkit from elements/ — do not edit.\n${imports}\n\n` +
      `export const projectElements: Record<string, any> = {\n${entries}\n};\n`,
  );
  return file;
};

/** The merged element bank, for `reelkit elements` and the gates. */
export const projectElementNames = () => {
  if (!existsSync(elementsDir)) return [];
  return readdirSync(elementsDir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith("_"))
    .filter((e) =>
      ["index.tsx", "index.ts"].some((f) =>
        existsSync(path.join(elementsDir, e.name, f)),
      ),
    )
    .map((e) => e.name)
    .sort();
};

/**
 * Bundle any entry point with the project's theme and elements wired in.
 *
 * Every bundle in the system goes through here, including the single-element
 * lab harnesses — an element previewed in core's grey and shipped in the
 * project's ink is a preview of something else.
 */
export const bundleEntry = async (entryPoint, { onProgress } = {}) => {
  mkdirSync(genDir, { recursive: true });
  // The caption faces ship WITH the engine (fonts/, OFL and Apache files,
  // licences beside them). A face named in a CSS stack used to render only if
  // it happened to be installed on the machine, and a missing one fell
  // through the stack without a word. src/fonts.ts loads every file in
  // fonts/fonts.json from the project's public dir before the first frame.
  cpSync(path.join(kitDir, "fonts"), path.join(publicDir, "fonts"), { recursive: true });
  const themeFile = writeTheme() ?? path.join(kitDir, "src", "theme.default.ts");
  const elementsFile =
    writeElements() ?? path.join(kitDir, "src", "elements.default.ts");

  return bundle({
    entryPoint,
    publicDir,
    onProgress,
    webpackOverride: (cfg) => ({
      ...cfg,
      resolve: {
        ...cfg.resolve,
        alias: {
          ...cfg.resolve?.alias,
          "reelkit-theme": themeFile,
          "reelkit-elements": elementsFile,
        },
      },
    }),
  });
};

/**
 * Bundle the project's main root. Returns a serve URL for renderMedia /
 * renderStill.
 *
 * `onProgress` is passed through so the callers keep their existing progress
 * lines — this function replaced a direct `bundle()` call in each renderer and
 * had to be a drop-in for it.
 */
export const bundleProject = ({ onProgress } = {}) =>
  bundleEntry(path.join(kitDir, "src", "index.ts"), { onProgress });

export { projectDir };
